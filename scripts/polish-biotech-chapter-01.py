def replace_between(content: str, start_heading: str, end_heading: str, replacement: str) -> str:
    pattern = re.compile(
        rf"{re.escape(start_heading)}\n\n.*?(?={re.escape(end_heading)})",
        re.S,
    )
    if not pattern.search(content):
        raise RuntimeError(f"Could not find block {start_heading!r}")
    return pattern.sub(replacement.rstrip() + "\n\n", content, count=1)


